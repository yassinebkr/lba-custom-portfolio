#!/usr/bin/env python3
"""Patch exactly the private SPRITES.HQR entry's containing archive in a v8 ZIP.

Keep original RELENT.EXE, voice banks, LBA.CFG, ISO, S003 and every other ZIP
entry byte-identical. Uses the owner-local HQR generated by the existing
native DOS adapter. No game content is committed or published.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import sys
from zipfile import ZipFile, BadZipFile, ZIP_DEFLATED

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = (ROOT / "output").resolve()


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def verify_guarded_executable(executable: bytes) -> None:
    script = ROOT / "scripts" / "runtime" / "prepare-jsdos8-bundle.py"
    spec = importlib.util.spec_from_file_location("r05_bundle_conversion", script)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    module.verify_boot_cinematics(executable)


def overlay(source: Path, patch_dir: Path, destination: Path) -> dict:
    source = source.resolve(strict=True)
    patch_dir = patch_dir.resolve(strict=True)
    destination = destination.resolve()
    for item in (source, patch_dir, destination):
        if not item.is_relative_to(OUTPUT):
            raise ValueError("Private game bundles and overlays must stay in ignored output/")
    if source == destination or destination.exists() or destination.is_symlink():
        raise ValueError("Choose a NEW private output archive, never overwrite a working bundle")
    if patch_dir.is_symlink():
        raise ValueError("Symlinked overlay directory forbidden")
    report_path = patch_dir / "report.json"
    overlay_path = patch_dir / "SPRITES.HQR"
    if report_path.is_symlink() or overlay_path.is_symlink():
        raise ValueError("Symlinked private overlay input forbidden")
    report = json.loads(report_path.read_text())
    if report.get("scene", {}).get("sceneIndex") != 43 or report.get("scene", {}).get("entryIndex") != 58:
        raise ValueError("Expected precisely the documented Museum sprite 58 probe")
    replacement = overlay_path.read_bytes()
    if sha(replacement) != report.get("privateOverlaySHA256"):
        raise ValueError("Overlay payload hash disagrees with private adapter report")
    if not 16 <= len(replacement) <= 16 * 1024 * 1024:
        raise ValueError("Unexpected size for the private sprite archive")
    with ZipFile(source, "r") as archive:
        if archive.testzip() is not None:
            raise ValueError("Private input bundle CRC mismatch")
        names = archive.namelist()
        if len(names) != len(set(names)):
            raise ValueError("Duplicate ZIP paths")
        required = ("RELENT.EXE", "SPRITES.HQR", "RESS.HQR", "S003.LBA",
                    ".jsdos/dosbox.conf", "LBA.CFG", "LBA.ISO")
        missing = set(required) - set(names)
        if missing:
            raise ValueError("Missing required v8 DOS files: " + ", ".join(sorted(missing)))
        if b"[autoexec]" not in archive.read(".jsdos/dosbox.conf").lower():
            raise ValueError("Expected known-good js-dos 8 startup")
        game_cfg = archive.read("LBA.CFG")
        if b"WaveDriver: W_SB16.DLL" not in game_cfg:
            raise ValueError("Expected owner-validated 16-bit stereo profile")
        verify_guarded_executable(archive.read("RELENT.EXE"))
        original_hqr = archive.read("SPRITES.HQR")
        if sha(original_hqr) != report.get("originalArchiveSHA256"):
            raise ValueError("Private DOS source archive differs from the source used for the overlay")
        if sha(archive.read("RESS.HQR")) != report.get("paletteArchiveSHA256"):
            raise ValueError("Private DOS palette differs from the source used for the sprite conversion")
        destination.parent.mkdir(parents=True, exist_ok=True)
        pending = destination.with_suffix(".tmp")
        if pending.is_symlink() or pending.exists():
            raise ValueError("Unsafe temporary private archive path")
        try:
            with ZipFile(pending, "w", compression=ZIP_DEFLATED, compresslevel=6) as out:
                for entry in archive.infolist():
                    data = replacement if entry.filename == "SPRITES.HQR" else archive.read(entry.filename)
                    out.writestr(copy.copy(entry), data)
            with ZipFile(pending) as updated:
                if updated.testzip() is not None:
                    raise ValueError("Edited DOS ZIP CRC mismatch")
                if updated.namelist() != names:
                    raise ValueError("Input ZIP entry list changed")
                if updated.read("SPRITES.HQR") != replacement:
                    raise ValueError("Edited sprite HQR bytes changed during packing")
                for name in names:
                    if name != "SPRITES.HQR" and updated.read(name) != archive.read(name):
                        raise ValueError("Unrelated DOS resource changed unexpectedly: " + name)
            pending.replace(destination)
        finally:
            pending.unlink(missing_ok=True)

    return {
        "source": str(source),
        "destination": str(destination),
        "modifiedZipEntries": ["SPRITES.HQR"],
        "preservedZipEntries": len(names) - 1,
        "sourceSHA256": sha(source.read_bytes()),
        "outputSHA256": sha(destination.read_bytes()),
        "scene": report["scene"],
        "gameplay": "not yet tested with the owner's original DOS runtime",
        "soundAndVOX": "contents byte-identical to input; playback remains an owner-run check",
    }


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--input", type=Path, required=True,
                   help="Existing private working r05-v8-english-voices-16bit.jsdos")
    p.add_argument("--overlay", type=Path, required=True,
                   help="Private output folder of museum-sprite-probe.mjs")
    p.add_argument("--out", type=Path, required=True,
                   help="New private r05-v8-museum-sprite58.jsdos")
    args = p.parse_args()
    try:
        print(json.dumps(overlay(args.input, args.overlay, args.out), indent=2))
    except (OSError, BadZipFile, ValueError, KeyError, json.JSONDecodeError) as exc:
        print("R06 private sprite overlay failed: " + str(exc), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
